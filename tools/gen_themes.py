#!/usr/bin/env python3
"""Generate the GTK and Qt colour files from the archive tokens.

    python3 tools/gen_themes.py

Writes:
  dotfiles/.config/archive/themes/gtk3-{day,night}.css
  dotfiles/.config/archive/themes/gtk4-{day,night}.css
  dotfiles/.config/qt6ct/colors/archive-{day,night}.conf
archive-mode links the right GTK file into ~/.config/gtk-{3,4}.0/gtk.css and
points qt6ct at the right colour scheme.
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "dotfiles", ".config")

TOKENS = {
    "day": dict(base="#C9C7C3", card="#D5D0CA", raised="#DDD9D3", graphite="#1E1D22", soft="#3E3D42",
                faded="#6E6C6D", rule="#4A4950", faint="#9C9995", accent="#34405E", wash="#7D8698",
                madder="#7A4A46", sage="#56664F", ochre="#7E7150", on_accent="#E2DED8", shade="rgba(30,29,34,0.18)"),
    "night": dict(base="#1C2F4D", card="#22385A", raised="#2A4268", graphite="#E6E1D6", soft="#C9CCD2",
                  faded="#8E9CB3", rule="#B8BFCC", faint="#4E6283", accent="#A9C4E4", wash="#A9C4E4",
                  madder="#D69A8E", sage="#A3B89A", ochre="#D2C296", on_accent="#1C2F4D", shade="rgba(8,16,30,0.40)"),
}

GTK = """/* Archive {mode} palette for GTK {ver} (adw-gtk3 / libadwaita named colours).
 * Generated by tools/gen_themes.py; edit the tokens there, not here.
 * Apps outside the shell keep IBM Plex Sans at their normal size (spec section 3). */

@define-color accent_color {accent};
@define-color accent_bg_color {accent};
@define-color accent_fg_color {on_accent};
@define-color destructive_color {madder};
@define-color destructive_bg_color {madder};
@define-color destructive_fg_color {on_accent};
@define-color success_color {sage};
@define-color success_bg_color {sage};
@define-color success_fg_color {on_accent};
@define-color warning_color {ochre};
@define-color warning_bg_color {ochre};
@define-color warning_fg_color {on_accent};
@define-color error_color {madder};
@define-color error_bg_color {madder};
@define-color error_fg_color {on_accent};

@define-color window_bg_color {card};
@define-color window_fg_color {graphite};
@define-color view_bg_color {raised};
@define-color view_fg_color {graphite};
@define-color headerbar_bg_color {card};
@define-color headerbar_fg_color {graphite};
@define-color headerbar_border_color {rule};
@define-color headerbar_backdrop_color {card};
@define-color headerbar_shade_color {shade};
@define-color headerbar_darker_shade_color {shade};
@define-color sidebar_bg_color {base};
@define-color sidebar_fg_color {graphite};
@define-color sidebar_backdrop_color {base};
@define-color sidebar_shade_color {shade};
@define-color secondary_sidebar_bg_color {base};
@define-color secondary_sidebar_fg_color {graphite};
@define-color card_bg_color {raised};
@define-color card_fg_color {graphite};
@define-color card_shade_color {shade};
@define-color dialog_bg_color {card};
@define-color dialog_fg_color {graphite};
@define-color popover_bg_color {card};
@define-color popover_fg_color {graphite};
@define-color popover_shade_color {shade};
@define-color thumbnail_bg_color {raised};
@define-color thumbnail_fg_color {graphite};
@define-color shade_color {shade};
@define-color scrollbar_outline_color {faint};
{extra}
"""

GTK_EXTRA = """
/* paper, not glass: square cut corners, no glow */
window, .background, decoration, headerbar, .titlebar, popover > contents,
menu, .menu, .csd.popup decoration {{ border-radius: 0; }}
button, entry, .card, list, row {{ border-radius: 0; }}
selection, *:selected {{ background-color: alpha({accent}, 0.22); color: {graphite}; }}
"""

QT_ROLES = [  # QPalette roles in qt6ct order
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text", "BrightText", "ButtonText",
    "Base", "Window", "Shadow", "Highlight", "HighlightedText", "Link", "LinkVisited",
    "AlternateBase", "NoRole", "ToolTipBase", "ToolTipText", "PlaceholderText",
]


def qt_line(t, disabled=False):
    fg = t["faded"] if disabled else t["graphite"]
    vals = {
        "WindowText": fg, "Button": t["card"], "Light": t["raised"], "Midlight": t["raised"], "Dark": t["faint"],
        "Mid": t["faint"], "Text": fg, "BrightText": t["on_accent"], "ButtonText": fg, "Base": t["raised"],
        "Window": t["card"], "Shadow": t["graphite"], "Highlight": t["accent"], "HighlightedText": t["on_accent"],
        "Link": t["accent"], "LinkVisited": t["wash"], "AlternateBase": t["card"], "NoRole": t["card"],
        "ToolTipBase": t["card"], "ToolTipText": t["graphite"], "PlaceholderText": t["faded"],
    }
    return ", ".join("#ff" + vals[r].lstrip("#").lower() for r in QT_ROLES)


def main():
    themes = os.path.join(ROOT, "archive", "themes")
    qtdir = os.path.join(ROOT, "qt6ct", "colors")
    os.makedirs(themes, exist_ok=True)
    os.makedirs(qtdir, exist_ok=True)
    for mode, t in TOKENS.items():
        for ver in (3, 4):
            css = GTK.format(mode=mode, ver=ver, extra=GTK_EXTRA.format(**t), **t)
            with open(os.path.join(themes, f"gtk{ver}-{mode}.css"), "w") as f:
                f.write(css)
        with open(os.path.join(qtdir, f"archive-{mode}.conf"), "w") as f:
            f.write("[ColorScheme]\n")
            f.write(f"active_colors={qt_line(t)}\n")
            f.write(f"disabled_colors={qt_line(t, disabled=True)}\n")
            f.write(f"inactive_colors={qt_line(t)}\n")
    print("themes written")


if __name__ == "__main__":
    main()
